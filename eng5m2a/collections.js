function collectionWordList(words) {
  return '<ul class="collection-words">' + words.map(w =>
    '<li><div><b lang="en">' + esc(w.en) + '</b><small>' + esc(w.ru) + '</small></div>' +
    '<button class="iconbtn" data-collection-audio="' + w.id +
    '" aria-label="Слушать ' + esc(w.en) + '">' + IC.playic + '</button></li>').join('') + '</ul>';
}
function collectionAudioEvents() {
  app.querySelectorAll('[data-collection-audio]').forEach(button => {
    button.onclick = () => speak(collectionAudio(button.dataset.collectionAudio), button);
  });
}
