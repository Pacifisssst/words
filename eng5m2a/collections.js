const COLLECTION_CHAPTER = '2c-17nov';
const collectionAudio = id => 'audio/collections/' + id + '.mp3';
function collectionChoice(word, group, listening) {
  const others = shuf(group.words.filter(other => other.id !== word.id)).slice(0, 2);
  return choice({
    qid: '2c: ' + word.en + (listening ? ' · audio' : ' · meaning'),
    prompt: listening ? 'Послушай и выбери перевод.' : 'Выбери английское слово.',
    audio: listening ? collectionAudio(word.id) : null,
    ru: listening ? null : word.ru,
    opts: listening ? [word.ru, ...others.map(w => w.ru)] : [word.en, ...others.map(w => w.en)],
    why: '<b>' + word.en + '</b> — ' + word.ru + '.',
    hint: 'Открой «Слова Module 2c» на карте и повтори трудные слова.',
    transcript: listening ? word.en : null,
  });
}
function collectionBuild(text, ru, id, audio) {
  return {
    type: 'build', qid: '2c: ' + id,
    prompt: audio ? 'Послушай и собери предложение.' : 'Собери предложение о вымышленном коллекционере.',
    ru: audio ? null : ru,
    audio: audio || null,
    tiles: shuf(text.split(' ')), accept: [text],
    why: '<b>' + text + '</b><br>' + ru,
    transcript: audio ? text : null,
    hint: 'Начни с I, My или They. Потом найди глагол.',
  };
}
